#!/usr/bin/env bash
# Build the Vega hls.js (Amazon's patch set on hls.js v1.5.11) and its W3C media polyfills
# into apps/tv-vega/vendor/vega-hls, where Metro picks it up as the `vega-hls` module
# (apps/tv-vega/metro.config.js). Both are Amazon-licensed, so the output is gitignored and
# this script rebuilds it on any machine. Without it the app still bundles; live video is off.
#
# Measured with this build on the Vega Virtual Device (specs/video-call-feasibility-2026-09-15.md
# section 7): IVS low-latency HLS at liveSyncDuration 3 plays 7.9 s behind the camera.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT="apps/tv-vega/vendor/vega-hls"
SPIKE="apps/tv-vega/spike/vendor"
PATCHES_URL="https://amzndevresources.com/vega/media-player/hls-rel-v1.5.11-r1.7-devices_scope.tar.gz"

mkdir -p "$OUT/dist"
if [ -f "$SPIKE/dist/hls.mjs" ] && [ -d "$SPIKE/polyfills" ]; then
  echo "reusing the spike's build in $SPIKE"
  cp "$SPIKE/dist/hls.mjs" "$OUT/dist/"
  rm -rf "$OUT/polyfills" && cp -r "$SPIKE/polyfills" "$OUT/"
else
  WORK="$(mktemp -d)"
  trap 'rm -rf "$WORK"' EXIT
  (cd "$WORK" && curl -sSLO "$PATCHES_URL" && tar -xzf "$(basename "$PATCHES_URL")")
  git clone -q --depth 1 --branch v1.5.11 https://github.com/video-dev/hls.js.git "$WORK/hls.js"
  (cd "$WORK/hls.js" && git apply -3 ../hls-rel/hls-patch/*.patch && npm install --silent && npm run build --silent)
  cp "$WORK/hls.js/dist/hls.mjs" "$OUT/dist/"
  rm -rf "$OUT/polyfills" && cp -r "$WORK/hls-rel/polyfills" "$OUT/"
fi

cat > "$OUT/package.json" <<'JSON'
{ "name": "vega-hls", "private": true, "version": "1.5.11-vega", "main": "index.js" }
JSON
cat > "$OUT/index.js" <<'JS'
// Generated by scripts/vega-hls.sh. hls.js with Amazon's Vega patches, plus the polyfills
// that give it a document, elements, TextDecoder and W3C media on Vega.
import * as HlsLib from "./dist/hls.mjs";
import Document from "./polyfills/DocumentPolyfill";
import Element from "./polyfills/ElementPolyfill";
import MiscPolyfill from "./polyfills/MiscPolyfill";
import TextDecoderPolyfill from "./polyfills/TextDecoderPolyfill";
import W3CMediaPolyfill from "./polyfills/W3CMediaPolyfill";

export const available = true;
export const Hls = HlsLib.Hls ?? HlsLib.default;
export const Events = HlsLib.Events ?? (HlsLib.default && HlsLib.default.Events);
export const ErrorTypes = HlsLib.ErrorTypes ?? (HlsLib.default && HlsLib.default.ErrorTypes);

let installed = false;
export function installPolyfills() {
  if (installed) return;
  installed = true;
  // hls.js clears timers it never set (handle -1 or undefined); Hermes on Vega throws
  // "clearTimeout called with an invalid handle" and the live reload loop dies.
  const g = globalThis;
  for (const name of ["clearTimeout", "clearInterval"]) {
    const orig = g[name];
    g[name] = (h) => {
      if (h === undefined || h === null || h === -1) return;
      try {
        orig(h);
      } catch {
        // an unknown handle is nothing to clear
      }
    };
    if (g.self && g.self !== g) g.self[name] = g[name];
    if (g.window && g.window !== g) g.window[name] = g[name];
  }
  Document.install();
  Element.install();
  TextDecoderPolyfill.install();
  W3CMediaPolyfill.install();
  MiscPolyfill.install();
  // hls.js picks the AAC profile from the user agent: anything not Firefox or Android is
  // forced to HE-AAC (a Chrome workaround), and Vega's decoder errors on that switch when IVS
  // sends AAC-LC. Its Android paths keep AAC-LC, which is what a Fire TV wants.
  if (!/android/i.test(g.navigator.userAgent)) g.navigator.userAgent = `${g.navigator.userAgent} Android`;
}
JS
echo "built $OUT"
